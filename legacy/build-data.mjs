import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const plain = html => html.replace(/<[^>]*>/g, ' ').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
const plants = fs.readdirSync(path.join(root, 'pages')).filter(file => /^\d+.*\.html$/.test(file)).map(file => {
    const html = fs.readFileSync(path.join(root, 'pages', file), 'utf8');
    const section = html.split(/<h2 id="出现篇目">/)[1]?.split(/<h2/)[0] || '';
    const poems = [...new Set([...plain(section).matchAll(/《([^》]+)》/g)].map(match => match[1]))];
    const image = html.match(/<img[^>]+src="([^"]+)"/);
    return { id: parseInt(file), name: file.replace(/^\d+|\.html$/g, '').trim(), url: `pages/${file}`, image: image ? `pages/${image[1].replace(/^\.\//, '')}` : '', poems, text: plain(html.replace(/<head>[\s\S]*?<\/head>/, '')) };
}).sort((a, b) => a.id - b.id);
fs.writeFileSync(path.join(root, 'plants-data.js'), `// Generated by node scripts/build-data.mjs; edit source HTML instead.\nwindow.PLANTS = ${JSON.stringify(plants)};\n`);
console.log(`Indexed ${plants.length} plants and ${new Set(plants.flatMap(plant => plant.poems)).size} poem titles.`);
